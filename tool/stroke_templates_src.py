def main():
    out = {}
    for lid, (ch, strokes) in T.items():
        pts = [p for s in strokes for p in s]
        xs, ys = [p[0] for p in pts], [p[1] for p in pts]
        out[lid] = {
            'letterId': lid, 'character': ch,
            'strokes': [[{'x': x, 'y': y} for x, y in s] for s in strokes],
            'boundingBox': {'top': min(ys), 'left': min(xs),
                            'width': round(max(xs) - min(xs), 3), 'height': round(max(ys) - min(ys), 3)},
        }
    with open(os.path.join(ROOT, 'stroke_templates.json'), 'w', encoding='utf-8') as f:
        json.dump(out, f, ensure_ascii=False, separators=(',', ':'))
    # Keep the "N strokes" hint on the canvas in step with the templates.
    lp = os.path.join(ROOT, 'letters.json')
    letters = json.load(open(lp, encoding='utf-8'))
    for group in ('vowels', 'consonants'):
        for l in letters[group]:
            if l['id'] in T:
                l['strokeCount'] = len(T[l['id']][1])
    with open(lp, 'w', encoding='utf-8') as f:
        json.dump(letters, f, ensure_ascii=False, separators=(',', ':'))
    print(f'wrote {len(out)} templates')


if __name__ == '__main__':
    main()
